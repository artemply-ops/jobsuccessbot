// Оферта и политика обработки ПДн. Реквизиты и цены приходят с сервера (.env: LEGAL_*, SUPPORT_EMAIL),
// поэтому для правки реквизитов код не нужен. Тексты черновые: перед запуском оплаты их должен посмотреть юрист.
import { useEffect, useState } from "react";
import { Link } from "react-router-dom";
import { api } from "../api";
import type { Product } from "./Billing";

type Pub = { products: Product[]; site: string; legal: { name: string; inn: string; status: string; email: string } };

function usePub() {
  const [pub, setPub] = useState<Pub | null>(null);
  useEffect(() => { api<Pub>("/billing/public").then(setPub).catch(() => {}); }, []);
  return pub;
}

function Seller({ pub }: { pub: Pub }) {
  const l = pub.legal;
  if (!l.name || !l.inn) return <div className="banner error">Черновик: реквизиты исполнителя ещё не заполнены.</div>;
  return <p>Исполнитель: {l.name}, {l.status || "самозанятый"}, ИНН {l.inn}. Связь: {l.email || "через бота в Telegram"}.</p>;
}

export function Offer() {
  const pub = usePub();
  if (!pub) return <div className="center muted">Загрузка…</div>;
  return (
    <div className="card stack legal">
      <h1>Публичная оферта</h1>
      <Seller pub={pub} />
      <h2>1. Предмет</h2>
      <p>Исполнитель предоставляет доступ к онлайн-сервису JobPilot ({pub.site}) и Telegram-боту: подготовка резюме,
        одностраничника и сопроводительного письма по материалам пользователя и описанию вакансии.</p>
      <h2>2. Цены и что входит</h2>
      <ul>{pub.products.map((p) => <li key={p.sku}>{p.title}: {p.price_rub} ₽ ({p.price_stars} звёзд в Telegram). {p.desc}.</li>)}</ul>
      <p>Первый пакет и одна правка предоставляются бесплатно. Тарифы на неделю и месяц действуют указанный срок,
        неиспользованный остаток по окончании срока сгорает. Разовые покупки бессрочны.</p>
      <h2>3. Оплата и акцепт</h2>
      <p>Оплата на сайте банковской картой через ЮKassa, в Telegram звёздами Telegram. Оплата означает согласие
        с офертой. Услуга считается оказанной в момент начисления лимита.</p>
      <h2>4. Возврат</h2>
      <p>Если лимит начислен, но пакет не удалось собрать по технической причине, лимит не списывается.
        Вопросы по оплате и возврату: по контактам исполнителя выше.</p>
      <h2>5. Ответственность</h2>
      <p>Сервис формирует документы только из фактов, которые сообщил пользователь, и проверяет их. Пользователь
        отвечает за достоверность своих сведений. Сервис не гарантирует приглашение на собеседование или трудоустройство.</p>
      <p className="muted small">Редакция от 15.11.2026. <Link to="/privacy">Политика обработки персональных данных</Link></p>
    </div>
  );
}

