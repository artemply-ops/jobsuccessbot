_GROWTH = {"ty": " Плюс {d} за один заход, неплохо.", "vy": " Плюс {d} за один заход."}


def norm(tone: str | None) -> str:
    return tone if tone in TONES else "neutral"


def _pick(variants: list[str], seed: int) -> str:
    return variants[seed % len(variants)]


def coverage(tone: str | None, covered: int, total: int) -> str:
    tone = norm(tone)
    if tone == "neutral" or total <= 0:
        return ""
    share = covered / total
    for low, variants in _COVERAGE[tone]:
        if share >= low:
            return _pick(variants, covered + total).format(c=covered, t=total)
    return ""


def score(tone: str | None, after: int | None, before: int | None = None) -> str:
    tone = norm(tone)
    if tone == "neutral" or after is None:
        return ""
    for low, variants in _SCORE[tone]:
        if after >= low:
            text = _pick(variants, after).format(a=after)
            if before is not None and after - before >= 5:
                text += _GROWTH[tone].format(d=after - before)
            return text
    return ""


def package(tone: str | None, sc: dict | None, cov: dict | None) -> str:
    """Одна реплика к готовому пакету: по требованиям вакансии, если они есть, иначе по баллу."""
    if cov and cov.get("req_total"):
        return coverage(tone, int(cov.get("req_covered") or 0), int(cov["req_total"]))
    if sc and sc.get("after") is not None:
        return score(tone, sc["after"], sc.get("before"))
    return ""
